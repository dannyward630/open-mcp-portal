// Command tokenscopes generates the table of operations that accept
// automation tokens from api/openapi.yaml (docs/automation-tokens.md,
// decision 58): every operation with an x-omp-token-scopes extension, keyed
// by "METHOD path" as the router names it, with its operation ID and the
// scopes any one of which suffices. Unannotated operations are not in the
// table, so they answer a token with 403 token_not_allowed (default deny).
//
// Usage: go run ./internal/tools/tokenscopes api/openapi.yaml out.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type operation struct {
	OperationID string   `yaml:"operationId"`
	Scopes      []string `yaml:"x-omp-token-scopes"`
}

var methods = []string{"get", "put", "post", "delete", "patch", "options", "head"}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: tokenscopes openapi.yaml out.go")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "tokenscopes:", err)
		os.Exit(1)
	}
}

type entry struct {
	key, id string
	scopes  []string
}

func run(specPath, out string) error {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	var doc struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return err
	}
	valid := map[string]bool{"platform:read": true, "platform:write": true, "servers:read": true, "servers:write": true}
	var entries []entry
	for path, item := range doc.Paths {
		for _, m := range methods {
			node, ok := item[m]
			if !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return fmt.Errorf("%s %s: %w", strings.ToUpper(m), path, err)
			}
			if len(op.Scopes) == 0 {
				continue
			}
			for _, s := range op.Scopes {
				if !valid[s] {
					return fmt.Errorf("%s %s: unknown token scope %q", strings.ToUpper(m), path, s)
				}
			}
			entries = append(entries, entry{key: strings.ToUpper(m) + " " + path, id: op.OperationID, scopes: op.Scopes})
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].key < entries[j].key })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/tokenscopes from api/openapi.yaml; DO NOT EDIT.\n\n")
	b.WriteString("package apitypes\n\n")
	b.WriteString("// TokenOperation is an operation that accepts automation tokens: its\n// operation ID and the scopes any one of which suffices (x-omp-token-scopes).\n")
	b.WriteString("type TokenOperation struct {\n\tOperationID string\n\tScopes      []string\n}\n\n")
	b.WriteString("// TokenOperations is every operation with x-omp-token-scopes, keyed by \"METHOD path\".\n")
	b.WriteString("var TokenOperations = map[string]TokenOperation{\n")
	for _, e := range entries {
		quoted := make([]string, len(e.scopes))
		for i, s := range e.scopes {
			quoted[i] = fmt.Sprintf("%q", s)
		}
		fmt.Fprintf(&b, "\t%q: {OperationID: %q, Scopes: []string{%s}},\n", e.key, e.id, strings.Join(quoted, ", "))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}
